#!/usr/bin/env bash
# Compare a fresh admin-surface report with the committed baseline.
# Env: BASE, REPORT, FAIL_ON_DRIFT. Writes drifted= to GITHUB_OUTPUT and a summary to GITHUB_STEP_SUMMARY.
set -uo pipefail

# The facts block carries every control fact with full addresses, one line each, tagged with its chain.
facts() { awk '/^```ownerwatch-facts$/{on=1;next} /^```$/{on=0} on' "$1"; }
# A baseline from before ownerwatch 0.11 has no facts block: compare each chain's table instead, not the Findings
# prose, and not the heading's label, so a repository rename is not drift.
tables() {
  awk '/^# /{keep=1; sub(/^# .* admin surface on /,"# "); print; next} /^## /{keep=0} keep' "$1"
}
generated_by() { sed -n 's/^_Generated by `ownerwatch probe` \([0-9][0-9.]*\) on .*/\1/p' "$1" | head -1; }

if [ ! -f "$BASE" ]; then
  echo "drifted=true" >> "$GITHUB_OUTPUT"
  {
    echo "## Admin surface: no baseline yet"
    echo
    echo "Commit \`$REPORT\` as \`$BASE\` to seed the baseline. Current report:"
    echo
    cat "$REPORT"
  } >> "$GITHUB_STEP_SUMMARY"
  echo "::warning::No baseline at $BASE. Commit $REPORT as $BASE to seed it."
  cat "$REPORT"
  if [ "$FAIL_ON_DRIFT" = "true" ]; then exit 1; fi
  exit 0
fi

compare=facts
if [ -z "$(facts "$BASE")" ] || [ -z "$(facts "$REPORT")" ]; then
  compare=tables
  echo "::warning::$BASE has no facts block, so only the summary table was compared and addresses are shortened. Commit $REPORT as $BASE to compare everything."
fi

if diff_out=$(diff <("$compare" "$BASE") <("$compare" "$REPORT")); then
  echo "drifted=false" >> "$GITHUB_OUTPUT"
  echo "## Admin surface unchanged" >> "$GITHUB_STEP_SUMMARY"
  echo "Admin surface unchanged."
  exit 0
fi

echo "drifted=true" >> "$GITHUB_OUTPUT"
{
  echo "## Admin surface changed"
  echo
  echo '```diff'
  echo "$diff_out"
  echo '```'
} >> "$GITHUB_STEP_SUMMARY"
echo "$diff_out"
was=$(generated_by "$BASE"); now=$(generated_by "$REPORT")
if [ -n "$was" ] && [ -n "$now" ] && [ "$was" != "$now" ]; then
  echo "::notice::The baseline came from ownerwatch $was and this run used $now. A newer version can see more of the same chain state, so some of this diff may be new detail, not a change on-chain."
fi
echo "::error::Admin surface changed since the committed report at $BASE. Review the diff, then commit $REPORT as $BASE if the change is expected."
if [ "$FAIL_ON_DRIFT" = "true" ]; then exit 1; fi
exit 0
