#!/usr/bin/env bash
# Offline test of compare.sh. Run from the repository root.
set -uo pipefail
dir=$(mktemp -d); trap 'rm -rf "$dir"' EXIT
fail=0

report() {  # report <file> <label> <ownerwatch version> <facts...>
  local f=$1 label=$2 version=$3; shift 3
  {
    echo "# $label admin surface on ethereum"; echo
    echo "| Address | Type | Controlled by | Detail |"; echo "|---|---|---|---|"
    echo '| `0xAAAA…AAAA` | proxy | `0xBBBB…BBBB` | - |'; echo
    echo "## Findings"; echo; echo "- some prose $version"; echo
    echo "## Full facts"; echo; echo '```ownerwatch-facts'; printf '%s\n' "$@"; echo '```'; echo
    echo "_Generated by \`ownerwatch probe\` $version on ethereum. Read-only; nothing was sent on-chain._"
  } >> "$f"
}

check() {  # check <name> <want exit> <want drifted> <base> <report> [fail_on_drift]
  local name=$1 want=$2 drifted=$3 base=$4 rep=$5 fod=${6:-true} out="$dir/out" got
  : > "$out"
  BASE=$base REPORT=$rep FAIL_ON_DRIFT=$fod GITHUB_OUTPUT=$out GITHUB_STEP_SUMMARY=$dir/summary ./compare.sh > "$dir/log" 2>&1
  got=$?
  if [ "$got" != "$want" ] || ! grep -qx "drifted=$drifted" "$out"; then
    echo "FAIL $name: exit $got (want $want), $(cat "$out") (want drifted=$drifted)"; cat "$dir/log"; fail=1
  else
    echo "ok   $name"
  fi
}

a="$dir/a.md"; b="$dir/b.md"
new() { rm -f "$a" "$b"; }

new; report "$a" "P" 0.11.0 "ethereum 0xAA owner 0x11"; report "$b" "P" 0.11.0 "ethereum 0xAA owner 0x11"
check "identical reports" 0 false "$a" "$b"

new; report "$a" "Old name" 0.11.0 "ethereum 0xAA owner 0x11"; report "$b" "org/new-name" 0.11.0 "ethereum 0xAA owner 0x11"
check "label change is not drift" 0 false "$a" "$b"

new; report "$a" "P" 0.11.0 "ethereum 0xAA signer 0x11" "ethereum 0xAA signer 0x22"; report "$b" "P" 0.11.0 "ethereum 0xAA signer 0x11" "ethereum 0xAA signer 0x33"
check "a Safe signer that the table never showed" 1 true "$a" "$b"

new; report "$a" "P" 0.11.0 "ethereum 0xAA owner 0x11112222333344445555666677778888aaaa0000"; report "$b" "P" 0.11.0 "ethereum 0xAA owner 0x11112222333344445555666677778888bbbb0000"
check "addresses equal in their first and last hex" 1 true "$a" "$b"

new
report "$a" "P" 0.11.0 "ethereum 0xAA owner 0x11"; report "$a" "P" 0.11.0 "base 0xBB owner 0x22"
report "$b" "P" 0.11.0 "ethereum 0xAA owner 0x11"; report "$b" "P" 0.11.0 "base 0xBB owner 0x99"
check "a change on the second chain" 1 true "$a" "$b"

new; report "$a" "P" 0.11.0 "ethereum 0xAA owner 0x11"; report "$b" "P" 0.12.0 "ethereum 0xAA owner 0x11"
check "new tool version, same facts" 0 false "$a" "$b"

new; report "$a" "P" 0.11.0 "ethereum 0xAA owner 0x11"; report "$b" "P" 0.11.0 "ethereum 0xAA owner 0x99"
check "fail-on-drift false only reports" 0 true "$a" "$b" false

check "no baseline" 1 true "$dir/missing.md" "$b"
check "no baseline, fail-on-drift false" 0 true "$dir/missing.md" "$b" false

# a baseline from before the facts block: every chain's table is compared, and the Findings prose is not
new
cat > "$a" <<'MD'
# P admin surface on ethereum

| `0xAAAA…AAAA` | proxy | `0xBBBB…BBBB` | - |

## Findings

- old wording

# P admin surface on base

| `0xCCCC…CCCC` | proxy | `0xDDDD…DDDD` | - |

## Findings

- old wording
MD
sed 's/old wording/new wording/; s/^# P /# renamed /' "$a" > "$b"
check "old baseline: prose and label do not count" 0 false "$a" "$b"
sed 's/0xDDDD…DDDD/0xEEEE…EEEE/' "$a" > "$b"
check "old baseline: the second chain's table counts" 1 true "$a" "$b"

exit $fail
